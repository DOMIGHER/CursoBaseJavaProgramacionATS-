public class OperadoresCombinados09 {

    public static void main(String[] args) {

        int num = 10;
        // Union de operaciones += suma
        num += 5;
        System.out.println("La suma es: " + num);

        int num1 = 10;
        // Union de operaciones -= resta
        num1 -= 5;
        System.out.println("La resta es: " + num1);

        int num2 = 10;
        // Union de operaciones *= multiplicacion
        num2 *= 5;
        System.out.println("La multi es: " + num2);

        int num3 = 10;
        // Union de operaciones /= division
        num3 /= 5;
        System.out.println("La div es: " + num3);

        int num4 = 10;
        // Union de operaciones %= porcentaje
        num4 %= 5;
        System.out.println("El resto es: " + num4);
    }
}
